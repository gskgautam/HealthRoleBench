"""Table 19: confidence intervals and significance tests for the headline comparisons.

Method (documented for the paper):
- 95% percentile bootstrap confidence intervals for Macro-F1: 1,000 resamples of test posts with
  replacement, seed 42. Invalid zero-shot answers count as wrong.
- Paired comparisons resample the same posts for both systems; the two-sided p-value is twice the
  smaller share of resampled differences on either side of zero (floored at 1/1,000).
- p-values are Holm-corrected within each family of comparisons.
- Where a system has three seeds (heads, encoders, Table 20), the per-post prediction is the
  majority vote over seeds (ties broken by seed 42); seed spread is reported in the source tables.

Families:
  T9   zero-shot classifiers, CI each; all classifier pairs (posts generated by neither model)
  T10  zero-shot vs frozen-backbone head, per open model (evaluation posts, off-diagonal)
  T12  standard encoders, CI each; encoder pairs (all 60,000 held-out-disease predictions)
  T18  each stress condition vs original, mean over the five classifiers (posts valid in that condition)
  T20  HealthRoleBench-initialised vs plain RoBERTa at each k (real test posts)

Run from PROJECT_ROOT:  python -m healthrolebench.analysis.significance --project-root .
"""
import argparse
import csv
import itertools
import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

from healthrolebench.common.data import DISEASES, digest, rows
from healthrolebench.curation.eval_set import load_eval
from healthrolebench.reporting.eval_tables import CLASSIFIERS, load_predictions
from healthrolebench.common.labels import INVALID, ROLES

B, SEED = 1000, 42
OUT = Path('data/experiments/significance_v1')


def encode(labels, values):
    index = {label: i for i, label in enumerate(labels)}
    return np.array([index.get(v, -1) for v in values], dtype=np.int16)    # -1 = invalid answer


def macro_f1(y, p, n_classes, present=None):
    """Macro-F1 over the last axis; y, p are (..., n) integer arrays."""
    scores = []
    for c in (present if present is not None else range(n_classes)):
        tp = ((y == c) & (p == c)).sum(-1)
        fp = ((y != c) & (p == c)).sum(-1)
        fn = ((y == c) & (p != c)).sum(-1)
        denominator = 2 * tp + fp + fn
        scores.append(np.where(denominator > 0, 2 * tp / np.maximum(denominator, 1), 0.0))
    return np.mean(scores, axis=0)


def resamples(n, rng):
    for _ in range(0, B, 100):
        yield rng.integers(0, n, size=(100, n))


def ci(y, p, n_classes):
    rng = np.random.default_rng(SEED)
    present = sorted(set(y.tolist()))
    boots = np.concatenate([macro_f1(y[idx], p[idx], n_classes, present) for idx in resamples(len(y), rng)])
    return float(macro_f1(y, p, n_classes, present)), float(np.percentile(boots, 2.5)), float(np.percentile(boots, 97.5))


def paired(y, pa, pb, n_classes):
    rng = np.random.default_rng(SEED)
    present = sorted(set(y.tolist()))
    diffs = np.concatenate([macro_f1(y[idx], pa[idx], n_classes, present) - macro_f1(y[idx], pb[idx], n_classes, present)
                            for idx in resamples(len(y), rng)])
    observed = float(macro_f1(y, pa, n_classes, present) - macro_f1(y, pb, n_classes, present))
    p = max(2 * min((diffs <= 0).mean(), (diffs >= 0).mean()), 1 / B)
    return observed, float(np.percentile(diffs, 2.5)), float(np.percentile(diffs, 97.5)), min(1.0, float(p))


def holm(pvalues):
    order = sorted(range(len(pvalues)), key=lambda i: pvalues[i])
    adjusted, running = [0.0] * len(pvalues), 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (len(pvalues) - rank) * pvalues[i]))
        adjusted[i] = running
    return adjusted


def majority(predictions_by_seed, seed_order):
    votes = Counter(predictions_by_seed[s] for s in seed_order)
    top = max(votes.values())
    winners = {label for label, n in votes.items() if n == top}
    return next(predictions_by_seed[s] for s in seed_order if predictions_by_seed[s] in winners)


def main(root):
    out = root / OUT
    out.mkdir(parents=True, exist_ok=False)
    results, comparisons = [], []        # (family, system, n, value, low, high) / (family, a, b, n, diff, low, high, p)
    key, _ = load_eval(root)
    gold = {i: r['intended_role'] for i, r in key.items()}
    source = {i: r['generator'] for i, r in key.items()}
    k = len(ROLES)
    original = load_predictions(root, 'original')

    # T9: zero-shot classifiers
    for model, pred in original.items():
        ids = [i for i in gold if source[i] != model]
        results.append(('T9', model, len(ids), *ci(encode(ROLES, [gold[i] for i in ids]), encode(ROLES, [pred[i] for i in ids]), k)))
    family = []
    for a, b in itertools.combinations(original, 2):
        ids = [i for i in gold if source[i] not in (a, b)]
        y = encode(ROLES, [gold[i] for i in ids])
        family.append(('T9', a, b, len(ids), *paired(y, encode(ROLES, [original[a][i] for i in ids]),
                                                       encode(ROLES, [original[b][i] for i in ids]), k)))
    comparisons.extend(family)

    # T10: zero-shot vs head (majority over seeds)
    head_path = root / 'data/experiments/probe_full_v1/eval_predictions.csv'
    if head_path.is_file():
        head = defaultdict(lambda: defaultdict(dict))
        for r in rows(head_path):
            head[r['classifier']][r['item_id']][r['seed']] = r['prediction']
        family = []
        for model in head:
            ids = [i for i in gold if source[i] != model]
            y = encode(ROLES, [gold[i] for i in ids])
            voted = [majority(head[model][i], ('42', '43', '44')) for i in ids]
            family.append(('T10', f'{model} head', f'{model} zero-shot', len(ids),
                           *paired(y, encode(ROLES, voted), encode(ROLES, [original[model][i] for i in ids]), k)))
        comparisons.extend(family)

    # T12: encoders (held-out-disease predictions pooled over diseases; majority over seeds)
    encoders = ('bert', 'roberta', 'distilbert')
    enc_pred, enc_gold = defaultdict(dict), {}
    for model in encoders:
        votes = defaultdict(dict)
        for disease in DISEASES:
            for seed in ('42', '43', '44'):
                for r in rows(root / 'data/experiments/encoder_transfer_v1' / model / disease / f'seed_{seed}' / 'predictions.csv'):
                    item = (r['generator'], r['sample_id'])
                    votes[item][seed] = r['prediction']
                    enc_gold[item] = r['label']
        enc_pred[model] = {item: majority(v, ('42', '43', '44')) for item, v in votes.items()}
    items = sorted(enc_gold)
    y = encode(ROLES, [enc_gold[i] for i in items])
    for model in encoders:
        results.append(('T12', model, len(items), *ci(y, encode(ROLES, [enc_pred[model][i] for i in items]), k)))
    comparisons.extend(('T12', a, b, len(items), *paired(y, encode(ROLES, [enc_pred[a][i] for i in items]),
                                                          encode(ROLES, [enc_pred[b][i] for i in items]), k))
                       for a, b in itertools.combinations(encoders, 2))

    # T18: each condition vs original, averaged over classifiers on the same posts
    for condition in ('cue-masked', 'paraphrased', 'adversarial'):
        stressed = load_predictions(root, condition)
        models = [m for m in stressed if m in original]
        if not models:
            continue
        ids = sorted(set.intersection(*(set(stressed[m]) for m in models)))
        y = encode(ROLES, [gold[i] for i in ids])
        rng = np.random.default_rng(SEED)
        present = sorted(set(y.tolist()))
        pairs = [(encode(ROLES, [stressed[m][i] for i in ids]), encode(ROLES, [original[m][i] for i in ids])) for m in models]
        diffs = np.concatenate([np.mean([macro_f1(y[idx], ps[idx], k, present) - macro_f1(y[idx], po[idx], k, present)
                                         for ps, po in pairs], axis=0) for idx in resamples(len(ids), rng)])
        observed = float(np.mean([macro_f1(y, ps, k, present) - macro_f1(y, po, k, present) for ps, po in pairs]))
        p = max(2 * min((diffs <= 0).mean(), (diffs >= 0).mean()), 1 / B)
        comparisons.append(('T18', condition, 'original', len(ids), observed, float(np.percentile(diffs, 2.5)),
                            float(np.percentile(diffs, 97.5)), min(1.0, float(p))))

    # T20: HealthRoleBench-initialised vs plain RoBERTa on real posts
    runs_dir = root / 'data/experiments/domain_adapt_v1/runs'
    if runs_dir.is_dir():
        with (root / 'data/external/constraint_covid19/test.csv').open(newline='', encoding='utf-8') as handle:
            real_gold = np.array([{'real': 0, 'fake': 1}[r['label']] for r in csv.DictReader(handle)], dtype=np.int16)
        runs = [json.loads(p.read_text()) for p in runs_dir.glob('*.json')]
        for size in sorted({r['k'] for r in runs}):
            voted = {}
            for start in ('hrb', 'roberta'):
                got = {str(r['seed']): r['test_predictions'] for r in runs if r['k'] == size and r['start'] == start}
                if len(got) == 3:
                    voted[start] = np.array([majority({s: got[s][i] for s in got}, ('42', '43', '44'))
                                             for i in range(len(real_gold))], dtype=np.int16)
            if len(voted) == 2:
                comparisons.append(('T20', f'hrb k={size}', f'roberta k={size}', len(real_gold),
                                    *paired(real_gold, voted['hrb'], voted['roberta'], 2)))
                results.append(('T20', f'hrb k={size}', len(real_gold), *ci(real_gold, voted['hrb'], 2)))
                results.append(('T20', f'roberta k={size}', len(real_gold), *ci(real_gold, voted['roberta'], 2)))

    # Holm correction within each family
    adjusted = []
    for name in dict.fromkeys(c[0] for c in comparisons):
        members = [c for c in comparisons if c[0] == name]
        adjusted.extend((*c, h) for c, h in zip(members, holm([c[-1] for c in members])))
    with (out / 'table_19_confidence_intervals.csv').open('x', newline='', encoding='utf-8') as handle:
        writer = csv.writer(handle)
        writer.writerow(('family', 'system', 'n', 'macro_f1', 'ci_low', 'ci_high'))
        writer.writerows(results)
    with (out / 'table_19_paired_tests.csv').open('x', newline='', encoding='utf-8') as handle:
        writer = csv.writer(handle)
        writer.writerow(('family', 'system_a', 'system_b', 'n', 'difference', 'ci_low', 'ci_high', 'p_value', 'p_holm'))
        writer.writerows(adjusted)
    (out / 'manifest.json').write_text(json.dumps(dict(
        resamples=B, seed=SEED, interval='95% percentile bootstrap', test='paired bootstrap, two-sided',
        correction='Holm within family', seeds_combined='majority vote over seeds 42-44',
        runner_sha256=digest(Path(__file__))), indent=2) + chr(10))
    print('Table 19 written:', len(results), 'intervals,', len(adjusted), 'paired tests')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Table 19: bootstrap confidence intervals and paired significance tests.')
    parser.add_argument('--project-root', required=True, type=Path)
    main(parser.parse_args().project_root.resolve())
