def pct(x):
    return 100.0 * float(x)


def coords(pairs):
    return ' '.join('(%s,%.2f)' % (x, y) for x, y in pairs)


def bar_axis(xcoords, series, ylabel, ymin, ymax, width, height, bar_width, legend_cols, extra=''):
    """series: list of (legend, color, [(x, y, err_or_None), ...])."""
    out = [r'\begin{tikzpicture}\begin{axis}[hrbbar, width=%s, height=%s, bar width=%s,'
           r' symbolic x coords={%s}, ylabel={%s}, ymin=%s, ymax=%s, legend columns=%d%s]'
           % (width, height, bar_width, ','.join(xcoords), ylabel, ymin, ymax, legend_cols, extra)]
    for name, color, pts in series:
        if any(p[2] is not None for p in pts):
            body = ' '.join('(%s,%.2f) +- (0,%.2f)' % (x, y, e or 0) for x, y, e in pts)
            out.append(r'\addplot[fill=%s, draw=none, error bars/.cd, y dir=both, y explicit,'
                       r' error bar style={line width=0.3pt}] coordinates {%s};' % (color, body))
        else:
            out.append(r'\addplot[fill=%s, draw=none] coordinates {%s};'
                       % (color, coords([(x, y) for x, y, _ in pts])))
        out.append(r'\addlegendentry{%s}' % name)
    out.append(r'\end{axis}\end{tikzpicture}')
    return '\n'.join(out)


def heatmap(labels, value, scale, cell=0.58, fmt='%.1f', lo=0):
    """Manual TikZ heatmap; value(r, c) -> float or None (shown as a dash)."""
    n = len(labels)
    out = [r'\begin{tikzpicture}[font=\tiny]']
    for i, r in enumerate(labels):
        y = (n - 1 - i) * cell
        out.append(r'\node[anchor=east] at (-0.05,%.3f) {%s};' % (y + cell / 2, {'COVID-19': 'COVID', 'Influenza': 'Flu'}.get(r, AB.get(r, r))))
        for j, c in enumerate(labels):
            x = j * cell
            v = value(r, c)
            if v is None:
                out.append(r'\fill[gray!12] (%.3f,%.3f) rectangle ++(%.3f,%.3f); \node at (%.3f,%.3f) {--};'
                           % (x, y, cell, cell, x + cell / 2, y + cell / 2))
            else:
                k = max(0, min(100, round((v - lo) * scale)))
                txt = 'white' if k > 60 else 'black'
                out.append(r'\fill[hrbD!%d!white] (%.3f,%.3f) rectangle ++(%.3f,%.3f); \node[text=%s] at (%.3f,%.3f) {%s};'
                           % (k, x, y, cell, cell, txt, x + cell / 2, y + cell / 2, fmt % v))
    for j, c in enumerate(labels):
        out.append(r'\node[anchor=north] at (%.3f,-0.03) {%s};' % (j * cell + cell / 2, {'COVID-19': 'COVID', 'Influenza': 'Flu'}.get(c, AB.get(c, c))))
    out.append(r'\draw[gray!50, line width=0.2pt] (0,0) grid[step=%.3f] (%.3f,%.3f);' % (cell, n * cell, n * cell))
    out.append(r'\node[font=\tiny] at (%.3f,-0.42) {Predicted role};' % (n * cell / 2))
    out.append(r'\node[font=\tiny, rotate=90] at (-0.78,%.3f) {True role};' % (n * cell / 2))
    out.append(r'\end{tikzpicture}')
    return '\n'.join(out)


def sub(caption, label, body, width):
    return (r'\subfloat[%s\label{%s}]{\begin{minipage}[b]{%s}\centering' '\n%s\n'
            r'\end{minipage}}' % (caption, label, width, body))


