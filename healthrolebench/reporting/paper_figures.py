                 r'(b)~Zero-shot Macro-F1 on the 1{,}500-post evaluation set; a classifier is not scored on its own posts. '
                 r'(c)~Zero-shot vs.\ linear-head Macro-F1 for the same backbones, averaged across generators. '
                 r'(d)~Paired bootstrap differences with 95\% CIs (1{,}000 resamples, Holm-adjusted) between zero-shot classifiers (A-B: A minus B) and of each linear head over its zero-shot backbone (Xh); G: GPT-4o, Q: Qwen, L: LLaMA-2, M: Mistral, E: Gemma.',
