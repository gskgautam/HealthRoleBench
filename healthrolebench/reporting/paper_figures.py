def subfig(width, axis_w, opts, plots, caption, label):
    """One panel: an IEEE-compatible \\subfloat (subfig, caption=false) holding a fixed-height parbox."""
    return (r'\subfloat[%s\label{%s}]{\parbox[t][2.9cm][t]{%s}{\centering\vspace*{0.3cm}'
            r'\begin{tikzpicture}\begin{axis}[%s, %s]%s\end{axis}\end{tikzpicture}}}' % (caption, label, width, BASE % axis_w, opts, plots))


def cats(xs, rotate=True):
    return 'symbolic x coords={%s}, xtick={%s}%s' % (','.join(xs), ','.join(xs), ', x tick label style={rotate=70,anchor=east}' if rotate else '')


def marks(series, legend, errs=False):
    """series: list of [(x, y[, err])]; offsets keep markers of one category apart."""
    n = len(series)
    off = [(k - (n - 1) / 2) * 1.5 for k in range(n)]
    out = []
    for k, pts in enumerate(series):
        m, sz = MARKS[k]
        opt = 'only marks,mark=%s,mark size=%.1fpt,color=%s' % (m, sz, COLORS[k])
        if off[k]:
            opt += ',xshift=%.1fpt' % off[k]
        if errs:
            opt += ',error bars/.cd,y dir=both,y explicit,error bar style={line width=0.3pt}'
            body = ''.join('(%s,%.2f)+-(0,%.2f)' % p for p in pts)
        else:
            body = ''.join('(%s,%.2f)' % p[:2] for p in pts)
        out.append(r'\addplot[%s] coordinates {%s};' % (opt, body))
    return ''.join(out) + r'\legend{%s}' % ','.join(legend)


def bars(series, legend, fills=None):
    fills = fills or COLORS
    out = [r'\addplot[fill=%s,draw=none] coordinates {%s};' % (fills[k], ''.join('(%s,%.2f)' % p for p in pts))
           for k, pts in enumerate(series)]
    return ''.join(out) + (r'\legend{%s}' % ','.join(legend) if legend else '')


def lines(series, legend, fmt='%.2f'):
    out = []
    for k, pts in enumerate(series):
        m, sz = MARKS[k]
        out.append(r'\addplot[mark=%s,mark size=%.1fpt,color=%s] coordinates {%s};'
                   % (m, sz + 0.1, COLORS[k], ''.join(('(%s,' + fmt + ')') % p for p in pts)))
    return ''.join(out) + r'\legend{%s}' % ','.join(legend)


def figure(subs, caption, label, extra_labels=()):
    return '\n'.join([r'\begin{figure*}[t]', r'\centering', '\\hfill\n'.join(subs),
                      r'\caption{%s}' % caption, r'\label{%s}' % label] + [r'\label{%s}' % l for l in extra_labels]
                     + [r'\vspace{-0.3cm}', r'\end{figure*}'])


